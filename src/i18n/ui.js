export function fmt(str, vars = {}) {
  return String(str ?? '').replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

export function errorMessage(lang, code, details) {
  const dict = UI[lang] || UI.es;
  return fmt(dict.errors[code] || dict.errors.SERVER_ERROR, details || {});
}
